ALTER PROCEDURE [dbo].[SP_GET_UNIT_CONVERSION_RATES]
(
    @BASEUNITID INT,
    @COMPANYID INT=0
)
AS
BEGIN
    SET NOCOUNT ON;

    
    -- TEMP WORK COPY OF YOUR TABLE
    
    DECLARE @UNITS TABLE (
        ID INT IDENTITY(1,1),
        UNITID INT,
        PARENTUNITID INT,
        RELATIONVALUE DECIMAL(18,5)
    );

    INSERT INTO @UNITS (UNITID, PARENTUNITID, RELATIONVALUE)
    SELECT 
        UNITID,
        PARENTUNITID,
        RELATIONVALUE
    FROM COMPOUND_UNIT

	--print 'here'
    
    -- RESULT TABLE
    
    DECLARE @RESULT TABLE (
        UNITID INT,
        CONVERSIONRATE DECIMAL(18,5)
    );

    -- INSERT THE BASE UNIT AS “1”
    INSERT INTO @RESULT VALUES (@BASEUNITID, 1);


    
    --  1. TRAVERSE UPWARD (PARENTS / ANCESTORS) 
    
    DECLARE 
        @CURR INT = @BASEUNITID,
        @PARENT INT,
        @RELATION DECIMAL(18,5) = 1,
        @ID INT;

    WHILE EXISTS (SELECT 1 FROM @UNITS WHERE UNITID = @CURR)
    BEGIN
        SELECT TOP 1
            @ID = ID,
            @PARENT = PARENTUNITID,
            @RELATION = @RELATION * RELATIONVALUE
        FROM @UNITS
        WHERE UNITID = @CURR;

        IF @PARENT IS NOT NULL
            INSERT INTO @RESULT VALUES (@PARENT, @RELATION);

        DELETE FROM @UNITS WHERE ID = @ID;

        SET @CURR = @PARENT;
    END;


    --  2. TRAVERSE DOWNWARD (CHILDREN / DESCENDANTS) 

    SET @CURR = @BASEUNITID;
    SET @RELATION = 1;

    WHILE EXISTS (SELECT 1 FROM @UNITS WHERE PARENTUNITID = @CURR)
    BEGIN
        SELECT TOP 1
            @ID = ID,
            @CURR = UNITID,
            @RELATION = @RELATION / RELATIONVALUE
        FROM @UNITS
        WHERE PARENTUNITID = @CURR;

        INSERT INTO @RESULT VALUES (@CURR, @RELATION);

        DELETE FROM @UNITS WHERE ID = @ID;
    END;


    -- FINAL OUTPUT WITH UNIT NAMES
    SELECT
        R.UNITID ID,
        UM.[NAME],
		@BASEUNITID DEFAULTUNITID,
        R.CONVERSIONRATE
    FROM @RESULT R
    LEFT JOIN UNIT UM
        ON UM.ID = R.UNITID
    ORDER BY R.CONVERSIONRATE DESC;
END

GO