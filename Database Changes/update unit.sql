ALTER PROCEDURE [dbo].[SP_UNIT_ADD_EDIT](
@ID INT=0,
@NAME NVARCHAR(150),
@SYMBOL NVARCHAR(30),
@REMARKS NVARCHAR(150)='',

-- AUDIT LOG START
@AUDITLOGCSV NVARCHAR(MAX) = NULL,
@IPADDRESS NVARCHAR(MAX) = NULL,
@MACADDRESS NVARCHAR(200) = NULL,
@COMPUTERNAME NVARCHAR(200) = NULL,
-- AUDIT LOG END

@COMPANYID INT =1,
@USERID NVARCHAR(20),   --IF ITEM ADDED THEN CREATED_BY ELSE MODIFIED BY
@RETURN NVARCHAR(20) ='' OUTPUT
)
AS
BEGIN TRY
BEGIN TRANSACTION

	
	DECLARE @RETURNVALUE INT;

	-- CHECK FOR DUPLICATE ENTRY
	IF EXISTS (SELECT * FROM UNIT WHERE [NAME]=@NAME AND COMPANYID=@COMPANYID  AND ID<>@ID) 
		RAISERROR('STATUS 409: DUPLICATE UNIT NAME', 15,1)
	IF EXISTS (SELECT * FROM UNIT WHERE SYMBOL=@SYMBOL AND COMPANYID=@COMPANYID  AND ID<>@ID)
		RAISERROR('STATUS 409: DUPLICATE UNIT SYMBOL', 15,1)

	IF (@ID<=0)  --ADD 
		BEGIN					
			INSERT INTO UNIT([NAME], SYMBOL, REMARKS, COMPANYID, CREATED_BY, CREATED_DATE) 
			VALUES (@NAME, @SYMBOL, @REMARKS, @COMPANYID, @USERID, GETDATE());

			SET @RETURN = SCOPE_IDENTITY();

		END
	ELSE --MODIFY 
		BEGIN
			-- CHECK IF ID EXISTS FOR COMPANYID
			IF NOT EXISTS(SELECT * FROM UNIT WHERE ID=@ID AND COMPANYID=@COMPANYID) 
				RAISERROR('STATUS 404: UNIT DOES NOT EXIST!', 15,1);

			UPDATE UNIT SET [NAME]=@NAME, SYMBOL=@SYMBOL, REMARKS=@REMARKS, MODIFIED_BY=@USERID, MODIFIED_DATE=GETDATE() WHERE ID=@ID;

			SET @RETURN = @ID
		END


COMMIT TRANSACTION

END TRY

BEGIN CATCH
ROLLBACK TRANSACTION

	 DECLARE 
        @ERRORMESSAGE NVARCHAR(MAX), @ERRORSEVERITY INT, @ERRORSTATE INT;
	SELECT 
        @ERRORMESSAGE = ERROR_MESSAGE(), @ERRORSEVERITY = ERROR_SEVERITY(), @ERRORSTATE = ERROR_STATE();
    RAISERROR (@ERRORMESSAGE, @ERRORSEVERITY, @ERRORSTATE);
	SET @RETURN='FAILURE';
	RETURN -100
END CATCH
go

